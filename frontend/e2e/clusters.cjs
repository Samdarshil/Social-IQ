/** Browser check of the YouTube engagement-clustering page (the hackathon brief). Backend :8000 and frontend :5173 must be running. */
const { chromium } = require('playwright')
const path = require('path')
const BASE = process.env.BASE_URL || 'http://localhost:5173'
const OUT = path.resolve(__dirname, '../../docs/screenshots')
const ok = (c, m) => { if (!c) throw new Error('FAILED: ' + m); console.log('  ✔ ' + m) }
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', (e) => errs.push(e.message))
  p.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g|ERR_|Failed to load resource/.test(m.text())) errs.push(m.text()) })
  await p.goto(BASE)
  await p.getByRole('button', { name: /Open the clustering analysis/ }).click()
  await p.waitForURL('**/app/clusters')
  await p.getByRole('heading', { name: 'Engagement clusters' }).waitFor()
  await p.getByText('Videos analysed').waitFor()
  ok(await p.getByText(/not predictions of future video popularity/).isVisible(), 'non-predictive banner shown')
  for (const h of ['How does engagement vary across categories?', 'Relationships between views, likes and comments', 'Can videos be grouped into distinct patterns?', 'What distinguishes each group?', 'Observations for creators'])
    ok(await p.getByRole('heading', { name: h }).isVisible(), 'section: ' + h)
  for (const l of ['Lower engagement', 'Moderate engagement', 'Higher engagement']) ok((await p.getByRole('heading', { name: l }).count()) === 1, 'cluster card: ' + l)
  ok(/6,229/.test(await p.locator('main').innerText()), 'US shows 6,229 videos analysed')
  await p.waitForTimeout(1200)
  await p.setViewportSize({ width: 1440, height: 3000 }); await p.waitForTimeout(2200)
  await p.screenshot({ path: path.join(OUT, '11-clusters.png') })
  await p.setViewportSize({ width: 1440, height: 900 })
  await p.getByLabel('Country').selectOption('IN')
  await p.getByText('not ordered the same way').first().waitFor({ timeout: 8000 })
  ok(true, 'India switches country and flags non-monotonic tiers honestly')
  await p.getByLabel('Country').selectOption('JP')
  await p.waitForFunction(() => /11,531/.test(document.body.innerText), null, { timeout: 8000 })
  ok(true, 'Japan loads (11,531 videos)')
  const m = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
  const mp = await m.newPage()
  await mp.goto(BASE); await mp.getByRole('button', { name: /Open the clustering analysis/ }).click(); await mp.waitForURL('**/app/clusters'); await mp.getByText('Videos analysed').waitFor()
  await mp.waitForTimeout(800)
  const over = await mp.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  ok(over <= 1, `no horizontal overflow on mobile (${over}px)`)
  ok(errs.length === 0, 'no page errors: ' + errs.join(' | ').slice(0, 200))
  await b.close()
})().catch((e) => { console.error(e.message); process.exit(1) })
